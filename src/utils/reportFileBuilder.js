function buildUsersSheet(wb, users) {
  const ws = wb.addWorksheet("Users");
  ws.columns = [
    { header: "Name", key: "name", width: 26 },
    { header: "Email", key: "email", width: 30 },
    { header: "Role", key: "role", width: 16 },
    { header: "Active", key: "active", width: 10 },
    { header: "Joined", key: "createdAt", width: 16 },
  ];
  styleHeader(ws.getRow(1));
  (users || []).forEach((u) => {
    ws.addRow({
      name: u.name || "",
      email: u.email || "",
      role: u.role || "",
      active: u.isActive ? "Yes" : "No",
      createdAt: fmtDate(u.createdAt),
    });
  });
}

function buildActivitySheet(wb, logs) {
  const ws = wb.addWorksheet("Activity Logs");
  ws.columns = [
    { header: "Actor", key: "actor", width: 24 },
    { header: "Action", key: "action", width: 26 },
    { header: "Entity", key: "entity", width: 16 },
    { header: "Entity ID", key: "entityId", width: 26 },
    { header: "Timestamp", key: "timestamp", width: 20 },
  ];
  styleHeader(ws.getRow(1));
  (logs || []).forEach((l) => {
    ws.addRow({
      actor: l.user?.name || "",
      action: l.action || "",
      entity: l.entity || "",
      entityId: l.entityId ? String(l.entityId) : "",
      timestamp: l.createdAt
        ? new Date(l.createdAt).toLocaleString("en-US")
        : "",
    });
  });
}

