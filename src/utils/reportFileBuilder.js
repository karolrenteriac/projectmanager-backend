async function buildReportExcel(filePath, ctx) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "ProjectManager Admin Reports";
  wb.created = new Date();

  buildSummarySheet(wb, ctx);
  buildProjectsSheet(wb, ctx.data.projects);
  buildTasksSheet(wb, ctx.data.tasks);
  buildDeliverablesSheet(wb, ctx.data.deliverables);
  buildUsersSheet(wb, ctx.data.users);
  buildActivitySheet(wb, ctx.data.activityLogs);

  await wb.xlsx.writeFile(filePath);
}

function styleHeader(row) {
  row.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: "FFFFFFFF" } };
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF6366F1" },
    };
    cell.alignment = { vertical: "middle" };
  });
  row.height = 20;
}

function buildSummarySheet(wb, ctx) {
  const ws = wb.addWorksheet("Summary");
  ws.columns = [
    { header: "Metric", key: "metric", width: 32 },
    { header: "Value", key: "value", width: 18 },
  ];
  styleHeader(ws.getRow(1));

  ws.addRow({ metric: "Report Title", value: ctx.title });
  ws.addRow({ metric: "Report Type", value: TYPE_LABELS[ctx.type] || ctx.type });
  ws.addRow({ metric: "Date Range", value: rangeLabel(ctx.dateRange) });
  ws.addRow({ metric: "Generated By", value: ctx.generatedBy || "Admin" });
  ws.addRow({ metric: "Generated At", value: fmtDate(new Date()) });
  ws.addRow({});

  const m = ctx.metrics || {};
  const metricRows = [
    ["Total Projects", m.totalProjects],
    ["Active Projects", m.activeProjects],
    ["Completed Projects", m.completedProjects],
    ["Overdue Projects", m.overdueProjects],
    ["Total Tasks", m.totalTasks],
    ["Completed Tasks", m.completedTasks],
    ["In-Progress Tasks", m.inProgressTasks],
    ["Overdue Tasks", m.overdueTasks],
    ["Total Deliverables", m.totalDeliverables],
    ["Pending Reviews", m.pendingReviews],
    ["Approved Deliverables", m.approvedDeliverables],
    ["Rejected Deliverables", m.rejectedDeliverables],
  ];
  metricRows.forEach(([metric, value]) =>
    ws.addRow({ metric, value: value ?? 0 })
  );
}

function buildProjectsSheet(wb, projects) {
  const ws = wb.addWorksheet("Projects");
  ws.columns = [
    { header: "Title", key: "title", width: 32 },
    { header: "Status", key: "status", width: 14 },
    { header: "Progress %", key: "progress", width: 12 },
    { header: "Coordinator", key: "coordinator", width: 24 },
    { header: "Total Tasks", key: "totalTasks", width: 12 },
    { header: "Completed Tasks", key: "completedTasks", width: 16 },
    { header: "Start Date", key: "startDate", width: 16 },
    { header: "End Date", key: "endDate", width: 16 },
    { header: "Created", key: "createdAt", width: 16 },
  ];
  styleHeader(ws.getRow(1));
  (projects || []).forEach((p) => {
    ws.addRow({
      title: p.title || "",
      status: p.status || "",
      progress: p.progress || 0,
      coordinator: p.coordinator?.name || "Unassigned",
      totalTasks: p.totalTasks ?? 0,
      completedTasks: p.completedTasks ?? 0,
      startDate: fmtDate(p.startDate),
      endDate: fmtDate(p.endDate),
      createdAt: fmtDate(p.createdAt),
    });
  });
}

